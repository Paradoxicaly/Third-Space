#!/usr/bin/env python3
"""Export the open-data candidate catalog as Supabase seed SQL (run in the SQL editor as the project owner).

Rows are inserted as status 'pending' by default so a moderator approves what becomes public. Pass
--status approved only as an explicit owner decision to publish the whole public-domain set at once.
Re-running is safe: existing IDs are skipped.

  python3 -I scripts/export-candidates-sql.py [--status pending|approved]
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ThirdSpace/Resources/OpenDataCandidates/california-candidates.json"
OUT = ROOT / "supabase/seed/california_candidates.sql"


def literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--status", choices=["pending", "approved"], default="pending")
    args = parser.parse_args()
    catalog = json.loads(SOURCE.read_text(encoding="utf-8"))
    sources = {s["id"]: s for s in catalog["sources"]}
    rows = []
    for p in catalog["places"]:
        s = sources[p["sourceID"]]
        provenance = {
            "sourceTitle": s["title"], "publisher": s["publisher"], "license": s["license"], "sourceURL": s["url"],
            "citation": s["citation"], "sourceRecordID": p["sourceRecordID"], "coordinateMethod": p["coordinateMethod"],
            "retrieved": catalog["retrieved"], "address": p["address"],
        }
        rows.append("  (" + ", ".join([
            literal(p["id"].lower()), literal(p["name"]), literal(p["category"]), "''",
            repr(p["latitude"]), repr(p["longitude"]), literal(args.status),
            literal(json.dumps(provenance, ensure_ascii=False)) + "::jsonb",
        ]) + ")")
    sql = [
        "-- GENERATED by scripts/export-candidates-sql.py from california-candidates.json. Do not edit by hand.",
        f"-- {len(rows)} public-domain open-data places, inserted as '{args.status}'. See docs/data/open-data-candidates.md.",
        "insert into public.places (id, name, category, description, latitude, longitude, status, source) values",
        ",\n".join(rows),
        "on conflict (id) do nothing;",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(sql), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} rows as {args.status}")


if __name__ == "__main__":
    main()
